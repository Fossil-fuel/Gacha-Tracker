"use strict";

const fs = require("fs");
const path = require("path");
const assert = require("../lib/assert");

const ROOT = path.join(__dirname, "..", "..");
const PRESETS = path.join(ROOT, "presets");

function readJson(rel) {
  return JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));
}

function check(name, fn) {
  try {
    fn();
    return { name, ok: true };
  } catch (err) {
    return {
      name,
      ok: false,
      error: err && err.message ? err.message : String(err),
      actual: err && err.actual,
      expected: err && err.expected,
    };
  }
}

module.exports = {
  name: "presets-json",
  title: "Game presets (JSON)",
  run() {
    const checks = [];

    checks.push(
      check("presets/index.json lists ids and files exist", () => {
        const index = readJson("presets/index.json");
        assert.ok(Array.isArray(index.presets) && index.presets.length > 0, "presets array required");
        index.presets.forEach((id) => {
          const file = path.join(PRESETS, id + ".json");
          assert.ok(fs.existsSync(file), "missing presets/" + id + ".json");
        });
      })
    );

    checks.push(
      check("each preset has id, name, server, and task arrays", () => {
        const index = readJson("presets/index.json");
        index.presets.forEach((id) => {
          const p = readJson("presets/" + id + ".json");
          assert.equal(p.id, id, id + " id matches filename");
          assert.ok(typeof p.name === "string" && p.name.length > 0, id + " has name");
          assert.ok(["america", "asia", "europe"].includes(p.server), id + " has valid server");
          assert.ok(Array.isArray(p.weeklies), id + " weeklies array");
          assert.ok(Array.isArray(p.endgame), id + " endgame array");
          p.weeklies.forEach((t) => {
            assert.ok(t.id || t.label, id + " weekly needs id or label");
          });
          p.endgame.forEach((t) => {
            assert.ok(t.id || t.label, id + " endgame needs id or label");
          });
        });
      })
    );

    checks.push(
      check("PGR Pain Cage unlock fields present in JSON preset", () => {
        const p = readJson("presets/pgr.json");
        const cage = (p.endgame || []).find((t) => t.id === "pain_cage");
        assert.ok(cage, "pain_cage task exists");
        assert.equal(cage.earliestCompleteDays, 2, "unlock day index 2");
        assert.equal(cage.earliestCompleteHour, 0, "unlock hour 0");
        assert.equal(cage.earliestCompleteMinute, 0, "unlock minute 0");
      })
    );

    checks.push(
      check("built app.js embeds GAME_PRESETS from JSON (incl. PGR unlock)", () => {
        const app = fs.readFileSync(path.join(ROOT, "app.js"), "utf8");
        assert.ok(app.includes("const GAME_PRESETS"), "GAME_PRESETS in app.js");
        assert.ok(app.includes("Punishing Grey Raven"), "PGR name embedded");
        assert.ok(app.includes('"pain_cage"') || app.includes("'pain_cage'"), "pain_cage id embedded");
        assert.ok(app.includes("earliestCompleteDays"), "unlock field embedded");
        const gen = fs.readFileSync(path.join(ROOT, "src", "01b-game-presets.js"), "utf8");
        assert.ok(gen.includes("GENERATED by build.js"), "generated marker present");
        assert.ok(gen.includes("pain_cage"), "generated file has pain_cage");
      })
    );

    const failed = checks.filter((c) => !c.ok);
    return {
      title: "Game presets (JSON contribution format)",
      checks,
      ok: failed.length === 0,
    };
  },
};
